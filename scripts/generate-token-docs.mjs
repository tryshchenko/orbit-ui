// Generates docs/tokens.md from the compiled @orbit/tokens package (run after `pnpm build:tokens`).
import { writeFileSync } from "node:fs";
import {
  densities,
  palette,
  semanticTokenNames,
  staticTokens,
  themeNames,
  themes,
  typeStyles,
} from "../packages/tokens/dist/index.js";

const esc = (v) => String(v).replace(/\|/g, "\\|");
const lines = [];
lines.push("# Design token reference", "");
lines.push("> Generated by `pnpm docs:tokens` from `@orbit/tokens`. Do not edit by hand.", "");
lines.push(
  'Every token is a CSS custom property prefixed `--orb-`. In TypeScript use `cssVar("color-accent")` → `var(--orb-color-accent)` or the typed `vars` map.',
  "",
);

lines.push("## Semantic tokens (per theme)", "");
lines.push(`| Token | ${themeNames.map((t) => themes[t].label).join(" | ")} |`);
lines.push(`| --- | ${themeNames.map(() => "---").join(" | ")} |`);
for (const name of semanticTokenNames) {
  lines.push(
    `| \`--orb-${name}\` | ${themeNames.map((t) => `\`${esc(themes[t].tokens[name])}\``).join(" | ")} |`,
  );
}
lines.push("");

lines.push("## Density", "", "| Token | Comfortable | Compact |", "| --- | --- | --- |");
for (const k of Object.keys(densities.comfortable))
  lines.push(`| \`--orb-${k}\` | ${densities.comfortable[k]} | ${densities.compact[k]} |`);
lines.push("");

lines.push(
  "## Typography roles",
  "",
  "| Role | Size | Line height | Weight | Tracking | Class |",
  "| --- | --- | --- | --- | --- | --- |",
);
for (const [role, s] of Object.entries(typeStyles))
  lines.push(
    `| ${role} | ${s.size} | ${s.leading} | ${s.weight} | ${s.tracking} | \`.orb-type-${role}\` |`,
  );
lines.push("");

lines.push(
  "## Static tokens",
  "",
  "Spacing, radius, blur, motion, z-index and font tokens are identical in every theme.",
  "",
  "| Token | Value |",
  "| --- | --- |",
);
for (const [k, v] of Object.entries(staticTokens)) lines.push(`| \`--orb-${k}\` | \`${esc(v)}\` |`);
lines.push("");

lines.push(
  "## Primitive palette",
  "",
  "Available as `--orb-palette-<hue>-<step>`. Components should prefer semantic tokens.",
  "",
);
for (const [hue, scale] of Object.entries(palette)) {
  if (typeof scale === "string") continue;
  lines.push(
    `**${hue}** — ${Object.entries(scale)
      .map(([s, v]) => `${s} \`${v}\``)
      .join(" · ")}`,
    "",
  );
}
writeFileSync(new URL("../docs/tokens.md", import.meta.url), lines.join("\n") + "\n");
console.log("wrote docs/tokens.md");
